    private static void sendJakartaMail(String host, String port, String user, String pass,
                                        String senderName, String toEmail, String subject,
                                        String htmlContent) throws Exception {

        Properties props = new Properties();
        props.put("mail.smtp.auth", "true");
        props.put("mail.smtp.starttls.enable", "true");
        props.put("mail.smtp.host", host);
        props.put("mail.smtp.port", port);

        // Reflection invocation for Jakarta Mail Session & MimeMessage
        Class<?> sessionClass = Class.forName("jakarta.mail.Session");
        Class<?> authenticatorClass = Class.forName("jakarta.mail.Authenticator");
        Class<?> passwordAuthClass = Class.forName("jakarta.mail.PasswordAuthentication");
        Class<?> messageClass = Class.forName("jakarta.mail.Message");
        Class<?> mimeMsgClass = Class.forName("jakarta.mail.internet.MimeMessage");
        Class<?> internetAddressClass = Class.forName("jakarta.mail.internet.InternetAddress");
        Class<?> transportClass = Class.forName("jakarta.mail.Transport");
        Class<?> recipientTypeClass = Class.forName("jakarta.mail.Message$RecipientType");

        Object auth = java.lang.reflect.Proxy.newProxyInstance(
                sessionClass.getClassLoader(),
                new Class[]{authenticatorClass},
                (proxy, method, args) -> {
                    if ("getPasswordAuthentication".equals(method.getName())) {
                        return passwordAuthClass.getConstructor(String.class, String.class).newInstance(user, pass);
                    }
                    return null;
                }
        );

        Method getInstance = sessionClass.getMethod("getInstance", Properties.class, authenticatorClass);
        Object session = getInstance.invoke(null, props, auth);

        Object message = mimeMsgClass.getConstructor(sessionClass).newInstance(session);

        Object fromAddr = internetAddressClass.getConstructor(String.class, String.class).newInstance(user, senderName);
        messageClass.getMethod("setFrom", Class.forName("jakarta.mail.Address")).invoke(message, fromAddr);

        Object toAddresses = internetAddressClass.getMethod("parse", String.class).invoke(null, toEmail);
        Object toType = recipientTypeClass.getField("TO").get(null);
        messageClass.getMethod("setRecipients", recipientTypeClass, Class.forName("[Ljakarta.mail.Address;"))
                .invoke(message, toType, toAddresses);

        messageClass.getMethod("setSubject", String.class).invoke(message, subject);
        messageClass.getMethod("setContent", Object.class, String.class).invoke(message, htmlContent, "text/html; charset=utf-8");

        transportClass.getMethod("send", messageClass).invoke(null, message);
    }
